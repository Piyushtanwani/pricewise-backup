export interface SeedStore {
  storeName: string;
  storeSlug: string;
  price: number;
  mrp?: number;
  productUrl: string;
  stockStatus?: 'IN_STOCK' | 'LIMITED' | 'OUT_OF_STOCK';
}

export interface SeedProduct {
  name: string;
  brand: string;
  bestPrice: number;
  mrp: number;
  rating: number;
  imageUrl: string;
  specs: string[];
  smartprixUrl?: string;
  stores: SeedStore[];
}


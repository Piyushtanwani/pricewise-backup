function makeStores(name: string, bestPrice: number, mrp: number): SeedStore[] {
  const enc = encodeURIComponent(name);
  const p1 = bestPrice;
  const p2 = Math.round(bestPrice * (1 + (Math.random() * 0.02 + 0.005)));
  const p3 = Math.round(bestPrice * (1 + (Math.random() * 0.03 + 0.01)));

  return [
    {
      storeName: 'Amazon',
      storeSlug: 'amazon',
      price: p1,
      mrp,
      productUrl: `https://www.amazon.in/s?k=${enc}`,
      stockStatus: 'IN_STOCK',
    },
    {
      storeName: 'Flipkart',
      storeSlug: 'flipkart',
      price: p2,
      mrp,
      productUrl: `https://www.flipkart.com/search?q=${enc}`,
      stockStatus: 'IN_STOCK',
    },
    {
      storeName: 'Croma',
      storeSlug: 'croma',
      price: p3,
      mrp,
      productUrl: `https://www.croma.com/searchB?q=${enc}`,
      stockStatus: 'IN_STOCK',
    },
  ];
}

